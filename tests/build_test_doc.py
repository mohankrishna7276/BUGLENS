"""Build docs/test_cases.md from MEASURED results.

* Static-analyzer column: computed live by running the analyzer.
* AI column: read from docs/ai_test_results.json if it exists (run tests/run_ai_tests.py first);
  otherwise it says 'Not run'. Optional manual verdicts can be put in docs/ai_verdicts.json
  as {"TC01": "PASS", ...} after you review the AI answers yourself.
"""
import json
import platform
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tests"))
from run_static_tests import run as run_static   # noqa: E402
from sample_cases import CASES                   # noqa: E402


def load(path):
    try:
        return json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", "<br>")


def code_cell(code):
    return "<br>".join(f"`{l.replace('|', chr(92) + '|')}`" if l.strip() else "&nbsp;" for l in code.rstrip("\n").splitlines())


static = {r["id"]: r for r in run_static()}
ai = load(ROOT / "docs" / "ai_test_results.json")
verdicts = load(ROOT / "docs" / "ai_verdicts.json")
n_pass = sum(r["status"] == "PASS" for r in static.values())

out = [f"# Test Cases and Evaluation Results\n",
       f"*Generated by `python tests/build_test_doc.py` on {date.today().isoformat()} "
       f"(Python {platform.python_version()}, {platform.system()}).*\n",
       "## How to read this table\n",
       "- **Actual result (static analyzer)** is *measured*: the analyzer was executed on the input shown.",
       "- **AI result (Groq)** is only filled when `python tests/run_ai_tests.py` has been run with a valid "
       "`GROQ_API_KEY`. Until then it says *Not run*. No AI results are invented.",
       "- **Status** is the static-analyzer verdict: PASS if every expected rule fired (or, for negative "
       "controls, nothing fired). It does **not** claim the AI explanation is correct.\n",
       f"**Static analyzer summary: {n_pass}/{len(CASES)} cases passed** "
       "(small, hand-written set; the rules were developed while looking at these cases, so this is a "
       "sanity check, not an accuracy estimate).\n",
       "## Evaluation table\n",
       "| Test case ID | Language | Input | Expected behavior | Actual result (static analyzer) | AI result (Groq) | Status |",
       "|---|---|---|---|---|---|---|"]
for c in CASES:
    r = static[c["id"]]
    a = ai.get(c["id"])
    if a is None:
        ai_txt = "Not run"
    elif a["status"] == "NOT RUN":
        ai_txt = "Not run: " + a["detail"]
    else:
        ai_txt = f"{a['summary']} (manual verdict: {verdicts.get(c['id'], 'pending review')})"
    out.append(f"| {c['id']} | {c['language']} | **{cell(c['title'])}**<br>{code_cell(c['code'])} | "
               f"{cell(c['expected'])} | {cell(r['actual'])} | {cell(ai_txt)} | {r['status']} |")
out.append("\n## Reproduce\n\n```bash\npython tests/run_static_tests.py          # static analyzer on all cases\n"
           "python tests/run_false_positive_probe.py  # valid programs must stay clean\n"
           "python tests/run_ai_tests.py              # needs GROQ_API_KEY\n"
           "python tests/build_test_doc.py            # rebuild this file\n```\n")
(ROOT / "docs" / "test_cases.md").write_text("\n".join(out), encoding="utf-8")
print("Wrote docs/test_cases.md")
